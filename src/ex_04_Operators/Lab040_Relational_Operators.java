package ex_04_Operators;

public class Lab040_Relational_Operators {
    public static void main(String[] args) {
        int a = 20;
        int b = 30;

        boolean c = a>b; //relational operator result will always be boolean

        System.out.println(c);

        int age_vani = 36;
        int age_shravan = 40;

        boolean result = age_shravan>age_vani;

        System.out.println(result);
    }
}
