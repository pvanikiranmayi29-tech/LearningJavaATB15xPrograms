package ex_04_Operators;

public class Lab037_Operators_Arithimetic_Operators {
    public static void main(String[] args) {
        //Arithimetic Operators
        // + (Addition)
        // - (Substraction)
        // * (Multiplication)
        // / (Division)
        // % (Modulus) - Remainder

        int a = 20;
        int b = 3;

        System.out.println(a+b);
        System.out.println(a-b);
        System.out.println(a*b);
        System.out.println(a/b);

        float c = 3.0f;

        System.out.println(a/c);

        System.out.println("a+b"); //this will print a+b as output and not 23 value
        // we should not use "" for mathematic operations

    }
}
